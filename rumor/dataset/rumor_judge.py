from llm_utils import call_llm


def is_valid_rumor(rumor_text):
    """判断一个谣言是否合格（有用信息）
    
    Args:
        rumor_text (str): 谣言文本内容
        
    Returns:
        bool: 如果谣言是有用信息则返回True，否则返回False
    """
    # 构建提示词，使用模板并替换{rumor}占位符
    prompt_template = '''
你是一名专门研究谣言信息与事实核查的分析专家。你的任务是判断给定的谣言文本是否包含有价值信息。请严格基于提供的谣言文本进行判断，不引入外部信息或推断。

**评估目标**
评估目标分为两类：有用信息（可被理解、讨论、传播或用于行动的具体信息）与无用信息（纯情绪、泛泛描述、缺乏锁定要素且无法形成有用推断）。

**判定标准**
无效信息
事件的主体为指代词（如“他”、“她”、“它”、某地、某xxx等）并且在其他地方无法找到明确的主体。
主体为过于宽泛的名词（如职业），无法确定具体主体。
时间锚点无法锚定到具体的时间点或时间范围，如（近日、周日、去年）
缺乏时间、地点、主体或事件等核心锚点，或仅包含泛泛的情绪、舆论、简短感叹、口号性语句，无法构成可讨论的事实或检验点。
仅描述背景、环境、散点式描述、或未指向具体事件的抽象观点。
仅包含单一维度信息（如仅有地点、仅有时间、仅有人物姓名而无事件描述），无法构成独立的有用陈述。
有效信息
融入了明确的时间、地点、主体与事件要素，或包含明确的主张/行动方向，且信息可被讨论、质疑或用于进一步分析。

**注意事项**
当谣言符合无效信息中的任何一条标准，被判定为无效信息。
无法确定是否为有效信息的情况，也被判定为无效信息。

**输入**
谣言：{rumor}

**输出**
仅输出一个中文短语，表示结果：有效信息 或 无效信息
不要输出任何其他内容。
'''
    
    # 替换占位符
    prompt = prompt_template.format(rumor=rumor_text)
    
    try:
        # 调用DeepSeek API获取结果
        result = call_llm('deepseek', prompt)
        
        # 检查是否成功获取结果
        if result and 'content' in result and result['content']:
            # 清理结果文本（去除多余空格和换行）
            content = result['content'].strip()
            
            # 判断结果是有用信息还是无用信息
            if content == '有效信息':
                return True
            elif content == '无效信息':
                return False
            else:
                # 如果返回格式不符合预期，记录日志并默认返回False
                print(f"警告：DeepSeek返回的结果格式不符合预期: {content}")
                return False
        else:
            print(f"错误：未能获取DeepSeek的有效响应")
            return False
            
    except Exception as e:
        print(f"调用DeepSeek API时发生错误: {str(e)}")
        return False


def main(rumors_to_test):
    """主函数：规范化结构"""
    # 统计结果
    total_valid = 0
    
    for i, rumor in enumerate(rumors_to_test, 2):  # 从2开始编号，因为第一个是示例
        result = is_valid_rumor(rumor)
        status = "合格" if result else "不合格"
        print(f"谣言{i} '{rumor}' 是否合格: {status}")
        if result:
            total_valid += 1
    
    print(f"\n测试结果统计:\n总谣言数: {len(rumors_to_test)}\n合格谣言数: {total_valid}\n合格率: {total_valid/len(rumors_to_test)*100:.2f}%")


